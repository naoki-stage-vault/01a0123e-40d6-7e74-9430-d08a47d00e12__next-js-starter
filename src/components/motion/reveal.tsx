"use client";

import { motion } from "motion/react";
import type { ReactNode } from "react";

/**
 * §1.6 Scroll reveal — subtle fade + slide (16px), 600ms, ease-out,
 * triggered once on view. No hover animation anywhere.
 */
export function Reveal({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 16 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-64px" }}
      transition={{ duration: 0.6, delay, ease: [0.25, 0.1, 0.25, 1] }}
    >
      {children}
    </motion.div>
  );
}
